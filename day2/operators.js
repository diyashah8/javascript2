// operators: operators are used to perform operations on variables and values.
// Types of operators:
// 1. Arithmetic operators:
let num1 = 20
let num2 = 12
// a. Addition + 
console.log(sum = num1 + num2)
// b. Subtraction -
console.log(diff = num1 - num2)
// c. multiplication *
console.log(product = num1 * num2)
// d. Division /
console.log(div = num1 / num2)
// e. Modulo %
console.log(reminder = num1 % num2)
// Exponential **
console.log(power = num1 ** num2)
// In case of string as a operands the + sign will acts as concat operators
let x = "diya"
let y = 21
console.log(x + y)

